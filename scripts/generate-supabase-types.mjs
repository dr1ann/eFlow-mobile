import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const projectRef = process.env.SUPABASE_PROJECT_REF?.trim();

function npxInvocation(args) {
  if (process.platform !== "win32") return { command: "npx", args };

  const npmExecutable = process.env.npm_execpath;
  const candidates = [
    npmExecutable ? resolve(dirname(npmExecutable), "npx-cli.js") : null,
    resolve(dirname(process.execPath), "node_modules", "npm", "bin", "npx-cli.js")
  ].filter(Boolean);
  const npxCli = candidates.find((candidate) => existsSync(candidate));

  if (!npxCli) {
    throw new Error("Unable to locate npm's npx CLI. Run this script through npm.");
  }

  return { command: process.execPath, args: [npxCli, ...args] };
}

if (!projectRef) {
  console.error("SUPABASE_PROJECT_REF is required to generate deployed Supabase types.");
  process.exitCode = 1;
} else {
  const invocation = npxInvocation([
    "--yes",
    "supabase@latest",
    "gen",
    "types",
    "typescript",
    "--project-id",
    projectRef,
    "--schema",
    "public"
  ]);
  const types = execFileSync(
    invocation.command,
    invocation.args,
    {
      stdio: ["ignore", "pipe", "inherit"],
      encoding: "utf8"
    }
  );
  writeFileSync(
    resolve(import.meta.dirname, "..", "src", "contracts", "database.types.ts"),
    `// Generated by npm run supabase:types. Do not edit manually.\n\n${types}`
  );
}
